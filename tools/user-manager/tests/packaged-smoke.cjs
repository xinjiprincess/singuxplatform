const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const {_electron}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const XLSX=require('xlsx');
const root=path.resolve(__dirname,'..');
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'singux-packaged-test-'));
const fixture=path.join(temp,'synthetic.xlsx');
const book=XLSX.utils.book_new();
XLSX.utils.book_append_sheet(book,XLSX.utils.aoa_to_sheet([['学号','姓名','手机号','邮箱'],['00001','Packaged Demo','13800138000','test@example.invalid']]),'Test');
XLSX.writeFile(book,fixture);
let app;
(async()=>{
  app=await _electron.launch({executablePath:process.env.SINGUX_PACKAGED_EXE || path.join(root,'release/SinguX-User-Manager-win32-x64/SinguX-User-Manager.exe'),args:['--user-data-dir='+temp]});
  const page=await app.firstWindow();const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.getByRole('heading',{name:'导入用户',exact:true}).waitFor();
  await page.getByText('导入账号密码表',{exact:true}).click();
  await page.getByText('API Key 管理',{exact:true}).first().click();
  const size=page.getByRole('combobox',{name:'显示条数'});
  await size.press('ArrowDown');
  await page.getByText('50 条 / 页',{exact:true}).last().click();
  await size.press('ArrowDown');
  await page.getByText('全部显示',{exact:true}).last().click();
  assert.equal(await app.evaluate(({app})=>app.isPackaged),true);
  await page.screenshot({path:path.join(root,'artifacts','packaged-client.png'),fullPage:true});
  await app.evaluate(({dialog},file)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]});},fixture);
  const parsed=await page.evaluate(()=>window.manager.choose({directory:false}));
  assert.equal(parsed.sheets.length,1);assert.deepEqual(parsed.issues,[]);
  const preview=await page.evaluate(()=>window.manager.preview({schoolCode:'test',usernamePrefix:'stu_',requireBoth:true}));
  assert.equal(preview.rows[0].userName,'test00001');assert.deepEqual(preview.rows[0].errors,[]);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({packaged:true,asarWorker:true,spreadsheetDependencies:true,networkRequests:0}));
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{if(app)app.process().kill();});
